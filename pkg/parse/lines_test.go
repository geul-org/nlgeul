//ff:func feature=parse type=rule control=iteration dimension=1
//ff:what TestLines — whole sentences: case particles and chains, auxiliaries, closings by kind, the copula, complements before 되다 and 아니다, 미정; "+" before every particle and between the pieces of a tail; dependent nouns, shortened 것, auxiliary verbs, determiners, conjunctions and naming endings of the closed sets
package parse

import (
	"strings"
	"testing"
)

func TestLines(t *testing.T) {
	cases := []struct{ in, want string }{
		{"이것은 문장을 분해한다", "이것+은:관형어|주어|목적어 문장+을:목적어|관형어 분해+한+다:서술어"},
		{"지시해서 가셨다고합니다", "지시+해서:서술어 가+시+었+다+고+합+니다:서술어"},
		{"가셨다고 합니다", "가+시+었+다+고:서술어 합+니다:서술어"},
		{"이것은 곰이다", "이것+은:관형어|주어|목적어 곰+이+다:서술어"},
		{"이것은 곰이 아니다", "이것+은:관형어|주어|목적어 곰+이:보어 아니+다:서술어"},
		{"이것은 곰이 되었다", "이것+은:관형어|주어|목적어 곰+이:보어 되+었+다:서술어"},
		{"물이 얼음이 됐어요", "물+이:보어|주어 얼음+이:보어|주어 됐+어+요:서술어"},
		{"권한이 사용되었다", "권한+이:주어 사용+되+었+다:서술어"},
		{"선생님께서 친구에게 집으로 나라의 힘만으로도 어제까지의 일만을 간다", "선생님+께서:주어 친구+에게:부사어 집+으로:부사어 나라+의:관형어 힘+만+으로+도:부사어 어제+까지+의:관형어 일+만+을:목적어 간+다:서술어"},
		{"그분이 잡히셨겠더군요", "그분+이:주어 잡히+시+었+겠+더+군+요:서술어"},
		{"먹었고 했지만 가면서 먹으면 불어서 봤어요", "먹+었+고:서술어 했+지만:서술어 가+면서:서술어 먹+으+면:서술어 불+어서:서술어 봤+어+요:서술어"},
		{"먹습니다 갑니다 가세요 먹죠 먹는다고 한다", "먹+습+니다:서술어 갑+니다:서술어 가+시+어+요:서술어 먹+지+요:서술어 먹+는+다+고:서술어 한+다:서술어"},
		{"분해한 학생인 가던 간다는 문제였다", "분해+한:관형어 학생+인:관형어 가+던:관형어 간+다+는:관형어 문제+였+다:서술어"},
		{"철수야 학교예요", "철수+야:독립어 학교+예요:서술어"},
		{"발전시키고 작성하고 시작됩니다", "발전+시키+고:서술어 작성+하+고:서술어 시작+됩+니다:서술어"},
		{"전략인거 아는거 할수 있는거지", "전략+인+거:미정 아+는+거:미정 할+수:미정 있+는+거+지:서술어"},
		{"없을 때까지 구경하는 거지", "없+을:관형어 때+까지:주어|목적어|부사어 구경+하+는:관형어 거+지:서술어"},
		{"먹는 것을 이게 그건 이걸 된다는게 좋다", "먹+는:관형어 것+을:목적어 이+게:주어 그+건:주어|목적어 이+걸:목적어 된+다+는+게:주어 좋+다:서술어"},
		{"이대로 말한대로 오늘따라 처음부터 간다", "이+대로:부사어 말한+대로:부사어 오늘+따라:부사어 처음+부터:주어|목적어|부사어 간+다:서술어"},
		{"작성해준 글을 해봐야 해주시고 되어있다", "작성+해+준:관형어 글+을:목적어|관형어 해+봐야:서술어 해+주+시+고:서술어 되+어+있+다:서술어"},
		{"그리고 이 사과가 어떤 사람에게 한 번 하지만 간다", "그리고:독립어 이:관형어 사과+가:주어 어떤:관형어 사람+에게:부사어 한:관형어 번:미정 하지만:독립어 간+다:서술어"},
		{"그것이 멋짐", "그것+이:주어 멋짐:미정"},
		{"이것이 훌륭함.", "이것+이:주어 훌륭+함.:서술어"},
		{"문제가 해결됨", "문제+가:주어 해결+됨:서술어"},
		{"그것은 문제임", "그것+은:관형어|주어|목적어 문제+임:서술어"},
		{"그는 밥을 먹음", "그+는:주어|목적어|관형어 밥+을:목적어|관형어 먹+음:서술어"},
		{"매우 GEUL 3 큰 예쁘다", "매우:미정 GEUL:미정 3:미정 큰:미정 예쁘+다:서술어"},
		{"밥을 학교를", "밥+을:목적어|관형어 학교를:미정"},
	}
	for _, c := range cases {
		out, err := Lines(c.in)
		if err != nil || strings.Join(out, " ") != c.want {
			t.Errorf("%s\n got %s (%v)", c.in, strings.Join(out, " "), err)
		}
	}
}
